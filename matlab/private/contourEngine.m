end

%% ========================================================================
% Hyperbolic zero-revolution
% ========================================================================

function [z, bestResidual, ok] = ...
        solveHyperbolicZeroRev( ...
        g, ...
        t, ...
        fast, ...
        targetTolerance)

    z = NaN;
    bestResidual = Inf;

    ok = false;

    [domainLeft, okBound] = ...
