% Stable velocity reconstruction from q = 4*pi^2-z
% ========================================================================

function [V1, V2, ok] = ...
        velocitiesFromUpperDistance( ...
        q, ...
        g, ...
        d, ...
        mu, ...
        L)

    V1 = ...
