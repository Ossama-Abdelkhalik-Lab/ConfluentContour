%% ========================================================================
% Cached semicircular contour nodes
% ========================================================================

function [e, weights] = contourKernel(n)
    % Avoid repeated exp() and weight allocation in the hot path.

    persistent eCache
    persistent wCache

    if isempty(eCache)

        eCache = ...
            cell(1, 513);

        wCache = ...
            cell(1, 513);

    end

    cacheable = ...
        n <= 512;

    index = ...
        n + 1;

    if cacheable && ...
            ~isempty(eCache{index})

        e = ...
            eCache{index};

        weights = ...
            wCache{index};

        return
    end

    e = ...
        exp( ...
        1i ...
        * pi ...
        * (0:n) ...
        / n ...
    );

    weights = [ ...
                   1, ...
                   2 * ones(1, n - 1), ...
                   1 ...
               ];

    if cacheable

        eCache{index} = e;
        wCache{index} = weights;

    end
end

%% ========================================================================
% Multi-revolution contour solver
% ========================================================================

function [zPair, status] = solveMultiRev(g, t, m, fast)

    zPair = ...
        [NaN NaN];

    status = ...
        -4;

    if m < 1
        return
    end

    if fast

        targetTolerance = ...
            1e-10;

        nodeCounts = ...
            [32 64 128];

        discriminantTolerance = ...
            1e-11;
    else

        targetTolerance = ...
            5e-13;

        nodeCounts = ...
            [64 128 256];

        discriminantTolerance = ...
            1e-13;

    end

    domainLeft = ...
        (2 * m * pi) ^ 2;

    domainRight = ...
        (2 * (m + 1) * pi) ^ 2;

    center = ...
        0.5 ...
        * (domainLeft + domainRight);

    halfWidth = ...
        0.5 ...
        * (domainRight - domainLeft);

    exclusions = ...
        [1 0.1 0.01];

    bestPair = ...
        [NaN NaN];

    bestResidual = ...
        Inf;

    bestStatus = ...
        -4;

    complexConfirmed = ...
        false;

    for exclusion = exclusions
        if exclusion >= halfWidth
            continue
        end

        radius = ...
            halfWidth ...
            - exclusion;

        for n = nodeCounts

            [J, momentsOK] = ...
                contourMomentsXi( ...
                g, ...
                t, ...
                m, ...
                center, ...
                radius, ...
                n ...
            );

            if ~momentsOK
                continue
            end

            momentScale = max(abs(J));
            if ~isfinite(momentScale) || momentScale <= realmin, continue; end
            J = J / momentScale;

            J0 = J(1);
            J1 = J(2);
            J2 = J(3);
            J3 = J(4);

            qa = ...
                J1 ^ 2 ...
                - J0 * J2;

            qb = ...
                J3 * J0 ...
                - J1 * J2;

            qc = ...
                J2 ^ 2 ...
                - J1 * J3;

            if ~all(isfinite([qa qb qc]))
                continue
            end

            coefficientScale = ...
                max([ ...
                     abs(J1 ^ 2), ...
                     abs(J0 * J2), ...
                     abs(J3 * J0), ...
                     abs(J1 * J2), ...
                     abs(J2 ^ 2), ...
                     abs(J1 * J3), ...
                     1 ...
                 ]);

            if abs(qa) <= ...
                    256 * eps * coefficientScale

                continue
            end

            discriminant = ...
                qb ^ 2 ...
                - 4 * qa * qc;

            discriminantScale = ...
                max([ ...
                     abs(qb ^ 2), ...
                     abs(4 * qa * qc), ...
                     1 ...
                 ]);

            if discriminant < 0 && ...
                    abs(discriminant) <= ...
                    discriminantTolerance ...
                    * discriminantScale

                discriminant = 0;

            end

            if discriminant < 0
                if exclusion == exclusions(end) && ...
                        n == nodeCounts(end)

                    complexConfirmed = true;

                end

                continue
            end

            sqrtDisc = ...
                sqrt(discriminant);

            %% -----------------------------------------------------------
            % Stable quadratic roots
            % ------------------------------------------------------------

            if sqrtDisc == 0

                xi1 = ...
                    -qb / (2 * qa);

                xi2 = ...
                    xi1;
            else

                if qb >= 0

                    qStable = ...
                        -0.5 ...
                        * (qb + sqrtDisc);
                else

                    qStable = ...
                        -0.5 ...
                        * (qb - sqrtDisc);

                end

                if abs(qStable) <= realmin

                    xi1 = ...
                        (-qb - sqrtDisc) ...
                        / (2 * qa);

                    xi2 = ...
                        (-qb + sqrtDisc) ...
                        / (2 * qa);
                else

                    xi1 = ...
                        qStable / qa;

                    xi2 = ...
                        qc / qStable;

                end
            end

            xiPair = ...
                sort([xi1 xi2]);

            if any(~isfinite(xiPair)) || ...
                    any(abs(xiPair) >= 1)

                continue
            end

            candidatePair = ...
                sort( ...
                center ...
                + radius .* xiPair ...
            );

            domainTolerance = ...
                1e-10 ...
                * max(1, domainRight);

            if candidatePair(1) < ...
                    domainLeft - domainTolerance || ...
                    candidatePair(2) > ...
                    domainRight + domainTolerance

                continue
            end

            % Separate the two poles before refining; the global moments can
            % locate both branches without yet meeting velocity accuracy.
            for j = 1:2
                candidate = candidatePair(j);

                for refinement = 1:3
                    localRadius = 0.4 * min([candidate - domainLeft, domainRight - candidate, diff(candidatePair)]);
                    if localRadius <= 0, break; end

                    for localNodes = [16 32 64 128]
                        [refined, refineOK] = contourPole(g, t, m, candidate, localRadius, localNodes);

                        if refineOK && abs(refined - candidate) < localRadius && ...
                                relativeResidual(refined, g, m, t) < relativeResidual(candidate, g, m, t)
                            candidate = refined;
                        end

                        if relativeResidual(candidate, g, m, t) <= 5e-13, break; end
                    end

                    if relativeResidual(candidate, g, m, t) <= 5e-13, break; end
                end

                candidatePair(j) = candidate;
            end

            residual1 = ...
                relativeResidual( ...
                candidatePair(1), ...
                g, ...
                m, ...
                t ...
            );

            residual2 = ...
                relativeResidual( ...
                candidatePair(2), ...
                g, ...
                m, ...
                t ...
            );

            residual = ...
                max( ...
                residual1, ...
                residual2 ...
            );

            if residual < bestResidual

                bestResidual = residual;

                bestPair = ...
                    candidatePair;

                rootScale = ...
                    max( ...
                    1, ...
                    max(abs(candidatePair)) ...
                );

                if abs( ...
                        candidatePair(2) ...
                        - candidatePair(1) ...
                    ) <= ...
                        1e-9 ...
                        * rootScale

                    bestStatus = 1;
                else

                    bestStatus = 0;

                end
            end

            if residual <= targetTolerance

                zPair = ...
                    candidatePair;

                status = ...
                    bestStatus;

                return
            end
        end
    end

    if all(isfinite(bestPair)) && ...
            bestResidual <= targetTolerance

        zPair = bestPair;
        status = bestStatus;
    elseif complexConfirmed

        status = 5;

    end
end

%% ========================================================================
% Centered/scaled multi-revolution moments
% ========================================================================

function [J, ok] = ...
        contourMomentsXi( ...
        g, ...
        t, ...
        m, ...
        center, ...
        radius, ...
        n)

    J = ...
        nan(1, 4);

    ok = ...
        false;

    [xi, weights] = ...
        contourKernel(n);

    zContour = ...
        center ...
        + radius .* xi;

    F = ...
        timeOfFlight( ...
        zContour, ...
        g, ...
        m ...
    ) ...
        - t;

    if any(~isfinite(F(:)))
        return
    end

    base = ...
        weights ...
        .* xi ...
        ./ F;

    J(1) = ...
        sum(real(base));

    J(2) = ...
        sum(real(base .* xi));

    xi2 = ...
        xi .^ 2;

    J(3) = ...
        sum(real(base .* xi2));

    J(4) = ...
        sum(real(base .* xi2 .* xi));

    ok = ...
        all(isfinite(J));

end

%% ========================================================================
% Hyperbolic lower bound
% ========================================================================

function [zLower, ok] = hyperbolicLowerBound(g, targetTime, fast)

    zLower = ...
        NaN;

    ok = ...
        false;

    tp = ...
        sqrt(g.y0) ...
        * ( ...
        g.y0 * sqrt(2) / 3 ...
        + g.a ...
    );

    if ~isfinite(tp) || ...
            tp <= 0 || ...
            targetTime <= 0 || ...
            targetTime >= tp

        return
    end

    if fast

        nSeries = 24;
    else

        nSeries = 48;

    end

    rho = ...
        0.25;

    theta = ...
        2 * pi ...
        * (0:nSeries - 1) ...
        / nSeries;

    e = ...
        exp(1i * theta);

    Tcircle = ...
        timeOfFlight( ...
        rho .* e, ...
        g, ...
        0 ...
    );

    if any(~isfinite(Tcircle(:)))
        return
    end

    Scircle = ...
        sqrt(Tcircle);

    a = ...
        zeros(1, 6);

    for k = 0:5

        coefficient = ...
            sum( ...
            Scircle ...
            .* exp(-1i * k * theta) ...
        ) ...
            / nSeries ...
            / rho ^ k;

        if abs(imag(coefficient)) > ...
                1e-8 ...
                * max( ...
                1, ...
                abs(real(coefficient)) ...
            )

            return
        end

        a(k + 1) = ...
            real(coefficient);

    end

    a1 = a(2);
    a2 = a(3);
    a3 = a(4);
    a4 = a(5);
    a5 = a(6);

    if ~all(isfinite([ ...
            a1 a2 a3 a4 a5 ...
        ])) || ...
            abs(a1) <= realmin

        return
    end

    b1 = ...
        1 / a1;

    b2 = ...
        -a2 / a1 ^ 3;

    b3 = ...
        (2 * a2 ^ 2 - a1 * a3) ...
        / a1 ^ 5;

    b4 = ...
        ( ...
        -5 * a2 ^ 3 ...
        + 5 * a1 * a2 * a3 ...
        - a1 ^ 2 * a4 ...
    ) ...
        / a1 ^ 7;

    b5 = ...
        ( ...
        14 * a2 ^ 4 ...
        - 21 * a1 * a2 ^ 2 * a3 ...
        + 6 * a1 ^ 2 * a2 * a4 ...
        + 3 * a1 ^ 2 * a3 ^ 2 ...
        - a1 ^ 3 * a5 ...
    ) ...
        / a1 ^ 9;

    w = ...
        -sqrt(tp);

    candidates = ...
        cumsum([ ...
                b1 * w, ...
                b2 * w ^ 2, ...
                b3 * w ^ 3, ...
                b4 * w ^ 4, ...
                b5 * w ^ 5 ...
            ]);

    for order = 5:-1:1

        zz = ...
            candidates(order);

        if ~isfinite(zz) || ...
                zz >= 0

            continue
        end

        tt = ...
            timeOfFlight( ...
            zz, ...
            g, ...
            0 ...
        );

        if ~isfinite(tt) || ...
                abs(imag(tt)) > ...
                1e-9 ...
                * max( ...
                1, ...
                abs(real(tt)) ...
            )

            continue
        end

        tt = ...
            real(tt);

        if tt >= 0 && ...
                tt < targetTime

            zLower = zz;
            ok = true;

            return
        end
    end

    %% -------------------------------------------------------------------
    % Physical y=0 boundary fallback
    % --------------------------------------------------------------------

    if g.b > 0

        zZero = ...
            -16 ...
            * asinh( ...
            sqrt( ...
            g.y0 ...
            / (2 * g.b) ...
        ) ...
        ) ^ 2;

        fractions = ...
            [0.9 0.98 0.995 0.9995];

        for fraction = fractions

            zz = ...
                fraction * zZero;

            tt = ...
                timeOfFlight( ...
                zz, ...
                g, ...
                0 ...
            );

            if ~isfinite(tt)
                continue
            end

            ttReal = ...
                real(tt);

            if abs(imag(tt)) <= ...
                    1e-9 ...
                    * max(1, abs(ttReal)) && ...
                    ttReal >= 0 && ...
                    ttReal < targetTime

                zLower = zz;
                ok = true;

                return
            end
        end
    end

    %% -------------------------------------------------------------------
    % Final bound search
    % --------------------------------------------------------------------

    validCandidates = ...
        candidates( ...
        isfinite(candidates) ...
        & candidates < 0 ...
    );

    if isempty(validCandidates)

        zz = -0.25;
    else

        zz = ...
            min(validCandidates);

    end

    for iteration = 1:48

        tt = ...
            timeOfFlight( ...
            zz, ...
            g, ...
            0 ...
        );

        if isfinite(tt)

            ttReal = ...
                real(tt);

            if abs(imag(tt)) <= ...
                    1e-9 ...
                    * max(1, abs(ttReal)) && ...
                    ttReal >= 0 && ...
                    ttReal < targetTime

                zLower = zz;
                ok = true;

                return
            end
        end

        zz = ...
            1.5 * zz;

    end
end

