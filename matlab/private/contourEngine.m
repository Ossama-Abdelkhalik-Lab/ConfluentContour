        g, ...
        t, ...
        fast ...
    );

    if ~okBound || ...
            ~isfinite(domainLeft) || ...
            domainLeft >= 0

        return
    end

    center = ...
        domainLeft / 2;

    halfWidth = ...
        -domainLeft / 2;

    if fast

        nodeCounts = ...
            [8 16 32];
    else

        nodeCounts = ...
            [16 32 64 128];

    end

    exclusionFractions = ...
        [1e-2 1e-3 1e-4];

    bestZ = NaN;

    for exclusionFraction = exclusionFractions

        radius = ...
            halfWidth ...
            * (1 - exclusionFraction);

        contourLeft = ...
            center - radius;

        contourRight = ...
            center + radius;

        for n = nodeCounts

            [candidate, contourOK] = ...
                contourPole( ...
                g, ...
                t, ...
                0, ...
                center, ...
                radius, ...
                n ...
            );

            if ~contourOK || ...
                    ~isfinite(candidate)

                continue
            end

            if candidate <= contourLeft || ...
                    candidate >= contourRight || ...
                    candidate >= 0

                continue
            end

            residual = ...
                relativeResidual( ...
                candidate, ...
                g, ...
                0, ...
                t ...
            );

            if residual < bestResidual

                bestResidual = residual;
                bestZ = candidate;

            end

            if residual <= targetTolerance

                z = candidate;
                ok = true;

                return
            end
        end
    end

    if isfinite(bestZ) && ...
            bestResidual <= targetTolerance

        z = bestZ;
        ok = true;

    end
end

%% ========================================================================
% One-pole contour in z
% ========================================================================

function [zStar, ok] = ...
        contourPole( ...
        g, ...
        t, ...
        m, ...
        center, ...
        radius, ...
        n)

    zStar = NaN;
    ok = false;

    if ~isfinite(center) || ...
            ~isfinite(radius) || ...
            radius <= 0

        return
    end

    [e, weights] = ...
        contourKernel(n);

    zContour = ...
        center ...
        + radius .* e;

    F = ...
        timeOfFlight( ...
        zContour, ...
        g, ...
        m ...
    ) ...
        - t;

    if any(~isfinite(F(:)))
        return
    end

    base = ...
        weights ...
        .* e ...
        ./ F;

    denominator = ...
        sum(real(base));

    numerator = ...
        sum( ...
        real( ...
        base .* e ...
    ) ...
    );

    scale = ...
        sum(abs(real(base)));

    if ~isfinite(denominator) || ...
            ~isfinite(numerator) || ...
            abs(denominator) <= ...
            128 * eps * max(1, scale)

        return
    end

    zStar = ...
        center ...
        + radius ...
        * numerator ...
        / denominator;

    if ~isfinite(zStar)
        return
    end

    zStar = ...
        real(zStar);

    ok = true;

end

