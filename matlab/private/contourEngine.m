        2 ...
        * ( ...
        2 * pi ...
        + rootZ ...
    ) ...
    );

    cv = ...
        -cos(w);

    sv2 = ...
        sin(w) ^ 2;

    if g.b < 0

        y = ...
            g.yend ...
            - 2 * g.b ...
            * sin(w / 2) ^ 2;
    else

        y = ...
            g.y0 ...
            + 2 * g.b ...
            * cos(w / 2) ^ 2;

    end

    if ~isfinite(y) || ...
            y <= 0

        return
    end

    dc = ...
        d * g.cs ...
        - cv;

    if d * g.cs * cv > 0

        denominator = ...
            d * g.cs ...
            + cv;

        if abs(denominator) <= realmin
            return
        end

        dc = ...
            ( ...
            sv2 ...
            - g.ss ^ 2 ...
        ) ...
            / denominator;

    end

    ratio = ...
        sqrt(g.r2 / g.r1);

    vr1 = ...
        sqrt(2) ...
        * ( ...
        dc ...
        + d * g.cs ...
        * (g.r2 - g.r1) ...
        / ( ...
        g.r1 ...
        * (ratio + 1) ...
    ) ...
    ) ...
        / sqrt(y);

    vr2 = ...
        -sqrt(2) ...
        * ( ...
        dc ...
        + d * g.cs ...
        * (g.r1 - g.r2) ...
        / ( ...
        g.r2 ...
        * (1 / ratio + 1) ...
    ) ...
    ) ...
        / sqrt(y);

    vt1 = ...
        sqrt(2) ...
        * ratio ...
        * g.ss ...
        / sqrt(y);

    vt2 = ...
        sqrt(2) ...
        * g.ss ...
        / ( ...
        ratio ...
        * sqrt(y) ...
    );

    velocityScale = ...
        sqrt(mu / L);

    V1 = ...
        ( ...
        vr1 * g.e1 ...
        + vt1 * g.t1 ...
    ) ...
        * velocityScale;

    V2 = ...
        ( ...
        vr2 * g.e2 ...
        + vt2 * g.t2 ...
    ) ...
        * velocityScale;

    ok = ...
        all(isfinite([V1; V2]));

end

function t = timeOfFlightSqrtY(q, g)
    u = 2 * asinh(sqrt(complex((g.y0 - q .^ 2) / (2 * g.b))));
    sh = sinh(u);
    f = (sh .* cosh(u) - u) ./ (sqrt(2) * sh .^ 3);
    small = abs(u) < 0.1;
    x = -u(small) .^ 2;
    f(small) = (2/3 + x .* (1/5 + x .* (17/420 + x .* (29/4200 + ...
        x .* (1181/1108800 + x * (1393481/9081072000)))))) / sqrt(2);
    t = q .* (q .^ 2 .* f + g.a);
end

function [z, y, ok] = solveHyperbolicSqrtY(g, target)
    % Same physical coordinate and bracketed contour safeguard as native time_q.
    % Bracket updates select contours; every accepted root is a contour moment.
    z = NaN; y = NaN; ok = false;
    lo = 0; hi = sqrt(g.y0); previous = NaN;

    for pass = 1:96
        center = (lo + hi) / 2; radius = (hi - lo) / 2;
        q = center;

        for n = [16 32 64]
            [e, weights] = contourKernel(n);
            base = weights .* e ./ (timeOfFlightSqrtY(center + radius * e, g) - target);
            denominator = sum(real(base));
            candidate = center + radius * sum(real(base .* e)) / denominator;
            if ~isfinite(candidate) || candidate <= lo || candidate >= hi, continue; end
            q = candidate;
            residual = abs(timeOfFlightSqrtY(q, g) - target) / target;

            if residual <= 128 * eps && abs(q - previous) <= 128 * eps * q
                y = q ^ 2;
                z = -16 * asinh(sqrt(max(0, (g.y0 - y) / (2 * g.b)))) ^ 2;
                ok = true; return
            end

            previous = q;
        end

        if mod(pass, 3) == 0, q = center; end
        if real(timeOfFlightSqrtY(q, g)) < target, lo = q; else, hi = q; end
    end
end