%% ========================================================================
% Standard velocity reconstruction
% ========================================================================

function [V1, V2, ok] = ...
        velocitiesFromZ( ...
        z, ...
        g, ...
        d, ...
        mu, ...
        L, ...
        m, yOverride)

    if nargin < 8, yOverride = NaN; end

    V1 = ...
        nan(3, 1);

    V2 = ...
        nan(3, 1);

    ok = ...
        false;

    if ~isfinite(z)
        return
    end

    if z >= 0

        u = ...
            sqrt(z) / 2 ...
            - m * pi;

        cv = ...
            cos(u);

        sv2 = ...
            sin(u) ^ 2;

        y = ...
            g.y0 ...
            + 2 * g.b ...
            * sin(u / 2) ^ 2;

        if g.b < 0

            y = ...
                g.yend ...
                - 2 * g.b ...
                * cos(u / 2) ^ 2;

        end
    else

        u = ...
            sqrt(-z) / 2;

        cv = ...
            cosh(u);

        sv2 = ...
            -sinh(u) ^ 2;

        y = ...
            g.y0 ...
            - 2 * g.b ...
            * sinh(u / 2) ^ 2;

    end

    if isfinite(yOverride), y = yOverride; end

    if ~isfinite(y) || ...
            y <= 0

        return
    end

    dc = ...
        d * g.cs ...
        - cv;

    if d * g.cs * cv > 0

        denominator = ...
            d * g.cs ...
            + cv;

        if abs(denominator) <= realmin
            return
        end

        dc = ...
            ( ...
            sv2 ...
            - g.ss ^ 2 ...
        ) ...
            / denominator;

    end

    if isfinite(yOverride)
        dc = (y - g.y0) / g.b - g.ss ^ 2 / (1 + g.cs);
    end

    ratio = ...
        sqrt(g.r2 / g.r1);

    vr1 = ...
        sqrt(2) ...
        * ( ...
        dc ...
        + d * g.cs ...
        * (g.r2 - g.r1) ...
        / ( ...
        g.r1 ...
        * (ratio + 1) ...
    ) ...
    ) ...
        / sqrt(y);

    vr2 = ...
        -sqrt(2) ...
        * ( ...
        dc ...
        + d * g.cs ...
        * (g.r1 - g.r2) ...
        / ( ...
        g.r2 ...
        * (1 / ratio + 1) ...
    ) ...
    ) ...
        / sqrt(y);

    vt1 = ...
        sqrt(2) ...
        * ratio ...
        * g.ss ...
        / sqrt(y);

    vt2 = ...
        sqrt(2) ...
        * g.ss ...
        / ( ...
        ratio ...
        * sqrt(y) ...
    );

    velocityScale = ...
        sqrt(mu / L);

    V1 = ...
        ( ...
        vr1 * g.e1 ...
        + vt1 * g.t1 ...
    ) ...
        * velocityScale;

    V2 = ...
        ( ...
        vr2 * g.e2 ...
        + vt2 * g.t2 ...
    ) ...
        * velocityScale;

    ok = ...
        all(isfinite([V1; V2]));

end

