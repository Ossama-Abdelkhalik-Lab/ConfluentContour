function [V1, V2, info] = contourEngine(R1, R2, dt, mu, H, M, fast)
    %CONTOURENGINE Fast, robust contour-integral Lambert solver.
    %
    % Based on the Negrete-Abdelkhalik contour-integral formulation.
    %
    % Main numerical features
    % -----------------------
    %   * Universal-variable Lambert formulation.
    %   * Direct contour-integral root extraction.
    %   * Stable series through the parabolic boundary z = 0.
    %   * Estimate-driven local contours near z = 0.
    %   * q = 4*pi^2 - z coordinate for long-way / upper-boundary cases.
    %   * Stable TOF and velocity reconstruction directly in q.
    %   * Residual-gated acceptance.
    %   * Centered/scaled multi-revolution moments.
    %   * Adaptive contour quadrature.
    %   * Cached contour nodes for reduced MATLAB overhead.
    %   * Explicit Nmax reporting.
    %
    %
    % INPUTS
    % ------
    % R1      3 x N initial position vectors
    % R2      3 x N final position vectors
    % dt      1 x N transfer times
    % mu      gravitational parameter
    %
    % H       One of:
    %
    %           3 x 1 reference angular-momentum / plane-normal vector
    %           3 x N plane-normal vectors
    %           1 x N explicit transfer directions (+1 / -1)
    %
    % M       maximum requested revolution count
    %
    % fast    true:
    %             optimized adaptive mode
    %
    %         false:
    %             higher-accuracy mode
    %
    %
    % OUTPUTS
    % -------
    % V1      3 x N x (2*M+1)
    % V2      3 x N x (2*M+1)
    %
    % info.status
    %       0    solved
    %       1    double/coalesced multi-revolution root
    %       5    physical solution does not exist
    %      -1    invalid/unprocessed
    %      -2    unresolved collinear geometry
    %      -4    numerical failure
    %
    % info.z
    %       universal-variable root
    %
    % info.qUpper
    %       q = 4*pi^2-z when the upper-boundary formulation was used
    %
    % info.relativeTimeResidual
    %       |Tcalc-Trequested| / Trequested
    %
    % info.Nmax
    %       largest physical revolution count established within [0,M]

    if nargin < 7 || isempty(fast)
        fast = true;
    end

    fast = logical(fast);

    %% ====================================================================
    % Input validation
    % =====================================================================

    validateattributes( ...
        R1, ...
        {'double'}, ...
        {'2d', 'nrows', 3, 'real'} ...
    );

    validateattributes( ...
        R2, ...
        {'double'}, ...
        {'size', size(R1), 'real'} ...
    );

    validateattributes( ...
        dt, ...
        {'double'}, ...
        {'real'} ...
    );

    validateattributes( ...
        mu, ...
        {'double'}, ...
        {'scalar', 'positive', 'finite', 'real'} ...
    );

    validateattributes( ...
        M, ...
        {'numeric'}, ...
        {'scalar', 'integer', 'nonnegative', 'finite'} ...
    );

    validateattributes( ...
        H, ...
        {'numeric'}, ...
        {'real'} ...
    );

    N = size(R1, 2);

    dt = reshape(dt, 1, []);

    assert( ...
        numel(dt) == N, ...
        'One transfer time is required per Lambert problem.' ...
    );

    %% ====================================================================
    % H / direction interpretation
    % =====================================================================

    sharedPlaneNormal = ...
        isequal(size(H), [3 1]);

    perCasePlaneNormal = ...
        isequal(size(H), [3 N]) ...
        && N > 1;

    explicitDirection = ...
        ~(sharedPlaneNormal || perCasePlaneNormal);

    rawCrossAll = ...
        cross(R1, R2, 1);

    if sharedPlaneNormal

        assert( ...
            all(isfinite(H)) && norm(H) > 0, ...
            'H must be a finite nonzero plane-normal vector.' ...
        );

        direction = ...
            sign( ...
            sum( ...
            rawCrossAll .* H, ...
            1 ...
        ) ...
        );
    elseif perCasePlaneNormal

        direction = ...
            sign( ...
            sum( ...
            rawCrossAll .* H, ...
            1 ...
        ) ...
        );
    else

        direction = ...
            reshape(H, 1, []);

        assert( ...
            numel(direction) == N, ...
            'One transfer direction per Lambert problem is required.' ...
        );

    end

    %% ====================================================================
    % Allocate output
    % =====================================================================

    K = ...
        2 * M + 1;

    V1 = ...
        nan(3, N, K);

    V2 = ...
        nan(3, N, K);

    info.status = ...
        -ones(N, K, 'int32');

    info.z = ...
        nan(N, K);

    info.qUpper = ...
        nan(N, 1);

    info.relativeTimeResidual = ...
        nan(N, K);

    info.revolutions = [ ...
                            0, ...
                            repelem(1:M, 2) ...
                        ];

    info.branch = [ ...
                       0, ...
                       repmat([-1 1], 1, M) ...
                   ];

    info.halfRevolution = ...
        zeros(N, 1, 'int32');

    info.Nmax = ...
        -ones(N, 1, 'int32');

    %% ====================================================================
    % Main solve loop
    % =====================================================================

    for i = 1:N

        r1mag = ...
            norm(R1(:, i));

        r2mag = ...
            norm(R2(:, i));

        if ~all(isfinite([ ...
                R1(:, i); ...
                R2(:, i); ...
                dt(i) ...
            ])) || ...
                r1mag <= 0 || ...
                r2mag <= 0 || ...
                dt(i) <= 0

            continue
        end

        %% ----------------------------------------------------------------
        % Normalize
        % -----------------------------------------------------------------

        L = ...
            max(r1mag, r2mag);

        g.r1 = ...
            r1mag / L;

        g.r2 = ...
            r2mag / L;

        g.e1 = ...
            R1(:, i) / r1mag;

        g.e2 = ...
            R2(:, i) / r2mag;

        rawH = ...
            cross(g.e1, g.e2);

        hn = ...
            norm(rawH);

        %% ----------------------------------------------------------------
        % Resolve direction and plane
        % -----------------------------------------------------------------

        if explicitDirection

            d = ...
                direction(i);

            if ~isfinite(d) || ...
                    abs(d) ~= 1

                continue
            end

            % Without an external plane normal, exact collinearity cannot
            % define an orbital plane.
            if hn < 32 * eps

                info.status(i, :) = -2;

                info.halfRevolution(i) = -1;

                continue
            end

            h = ...
                rawH ...
                * (d / hn);
        else

            if sharedPlaneNormal

                href = ...
                    H(:);
            else

                href = ...
                    H(:, i);

            end

            if ~all(isfinite(href)) || ...
                    norm(href) <= 0

                continue
            end

            % Direction inferred from endpoint cross product whenever it is
            % numerically meaningful.
            if hn >= 32 * eps

                d = ...
                    sign(dot(rawH, href));

                if d == 0
                    d = 1;
                end
            else

                % At exact antipodal geometry the plane normal supplies the
                % otherwise missing plane. d=+1 means motion consistent
                % with the supplied angular-momentum direction.
                d = 1;

            end

            % For nearly collinear vectors, do NOT normalize the tiny
            % endpoint cross product. Use the supplied plane normal.
            if hn < 1e-5

                h = ...
                    href ...
                    - g.e1 ...
                    * dot(g.e1, href);

                hNorm = ...
                    norm(h);

                if hNorm <= 32 * eps

                    info.status(i, :) = -2;

                    continue
                end

                h = ...
                    h / hNorm;

                % Align with supplied H.
                if dot(h, href) < 0
                    h = -h;
                end
            else

                h = ...
                    rawH ...
                    * (d / hn);

            end
        end

        if hn < 1e-4
            info.halfRevolution(i) = 1;
        end

        %% ----------------------------------------------------------------
        % Local transverse bases
        % -----------------------------------------------------------------

        g.t1 = ...
            cross(h, g.e1);

        g.t2 = ...
            cross(h, g.e2);

        %% ----------------------------------------------------------------
        % Universal-variable geometry
        % -----------------------------------------------------------------

        g.cs = ...
            norm(g.e1 + g.e2) / 2;

        g.ss = ...
            norm(g.e2 - g.e1) / 2;

        p = ...
            sqrt(g.r1 * g.r2);

        g.a = ...
            d ...
            * sqrt(2) ...
            * p ...
            * g.cs;

        g.b = ...
            sqrt(2) ...
            * g.a;

        qGeom = ...
            (g.r1 - g.r2) ...
            / ( ...
            sqrt(g.r1) ...
            + sqrt(g.r2) ...
        );

        if d > 0

            g.y0 = ...
                qGeom ^ 2 ...
                + 2 * p * g.ss ^ 2 ...
                / (1 + g.cs);
        else

            g.y0 = ...
                qGeom ^ 2 ...
                + 2 * p ...
                * (1 + g.cs);

        end

        g.yend = ...
            qGeom ^ 2 ...
            + 2 * p * g.ss ^ 2 ...
            / (1 + g.cs);

        %% ----------------------------------------------------------------
        % Dimensionless time
        % -----------------------------------------------------------------

        t = ...
            dt(i) ...
            * sqrt(mu) ...
            / L ^ (3/2);

        %% ================================================================
        % Zero revolution
        % =================================================================

        [z0, status0, qUpper, hyperbolicY] = ...
            solveZeroRev( ...
            g, ...
            t, ...
            fast ...
        );

        info.status(i, 1) = ...
            status0;

        info.z(i, 1) = ...
            z0;

        info.qUpper(i) = ...
            qUpper;

        if status0 >= 0 && ...
                isfinite(z0)

            if isfinite(qUpper)

                residual = ...
                    relativeResidualUpper( ...
                    qUpper, ...
                    g, ...
                    t ...
                );

                [v1, v2, okVelocity] = ...
                    velocitiesFromUpperDistance( ...
                    qUpper, ...
                    g, ...
                    d, ...
                    mu, ...
                    L ...
                );
            else

                residual = ...
                    relativeResidual( ...
                    z0, ...
                    g, ...
                    0, ...
                    t ...
                );

                [v1, v2, okVelocity] = ...
                    velocitiesFromZ( ...
                    z0, ...
                    g, ...
                    d, ...
                    mu, ...
                    L, ...
                    0, hyperbolicY ...
                );

                if isfinite(hyperbolicY)
                    residual = abs(timeOfFlightSqrtY(sqrt(hyperbolicY), g) - t) / t;
                end
            end

            info.relativeTimeResidual(i, 1) = ...
                residual;

            if okVelocity

                V1(:, i, 1) = ...
                    v1;

                V2(:, i, 1) = ...
                    v2;
            else

                info.status(i, 1) = -4;

            end
        end

        %% ================================================================
        % No multi-revolution request
        % =================================================================

        if M == 0

            info.Nmax(i) = 0;

            continue
        end

        %% ================================================================
        % Multi revolution
        % =================================================================

        numericalGap = false;

        for m = 1:M

            kLow = ...
                2 * m;

            kHigh = ...
                2 * m + 1;

            [zPair, statusM] = ...
                solveMultiRev( ...
                g, ...
                t, ...
                m, ...
                fast ...
            );

            if statusM == 5

                info.status(i, kLow:K) = 5;

                info.Nmax(i) = ...
                    int32(m - 1);

                break
            end

            if statusM < 0

                info.status(i, kLow:kHigh) = ...
                    statusM;

                numericalGap = true;

                continue
            end

            zPair = ...
                sort(real(zPair));

            for j = 1:2

                k = ...
                    kLow + j - 1;

                z = ...
                    zPair(j);

                residual = ...
                    relativeResidual( ...
                    z, ...
                    g, ...
                    m, ...
                    t ...
                );

                info.status(i, k) = ...
                    statusM;

                info.z(i, k) = ...
                    z;

                info.relativeTimeResidual(i, k) = ...
                    residual;

                [v1, v2, okVelocity] = ...
                    velocitiesFromZ( ...
                    z, ...
                    g, ...
                    d, ...
                    mu, ...
                    L, ...
                    m ...
                );

                if okVelocity

                    V1(:, i, k) = ...
                        v1;

                    V2(:, i, k) = ...
                        v2;
                else

                    info.status(i, k) = -4;

                    numericalGap = true;

                end
            end

            if m == M
                if numericalGap

                    info.Nmax(i) = -1;
                else

                    info.Nmax(i) = ...
                        int32(M);

                end
            end
        end
    end
end

%% ========================================================================
% Universal-variable time of flight
% ========================================================================

function t = timeOfFlight(z, g, m)

    u = ...
        sqrt(complex(z)) / 2;

    v = ...
        u - m * pi;

    s = ...
        sin(v);

    c = ...
        cos(v);

    y = ...
        g.y0 ...
        + 2 * g.b ...
        .* sin(v / 2) .^ 2;

    if g.b < 0

        y = ...
            g.yend ...
            - 2 * g.b ...
            .* cos(v / 2) .^ 2;

    end

    f = ...
        (u - s .* c) ...
        ./ (sqrt(2) .* s .^ 3);

    %% -------------------------------------------------------------------
    % Stable z ~= 0 expansion
    % --------------------------------------------------------------------

    small = ...
        (m == 0) ...
        & (abs(v) < 0.1);

    if any(small(:))

        v2 = ...
            v(small) .^ 2;

        f(small) = ...
            ( ...
            2/3 ...
            + v2 .* ( ...
            1/5 ...
            + v2 .* ( ...
            17/420 ...
            + v2 .* ( ...
            29/4200 ...
            + v2 .* ( ...
            1181/1108800 ...
            + v2 .* ...
            (1393481/9081072000) ...
        ) ...
        ) ...
        ) ...
        ) ...
        ) ...
            / sqrt(2);

    end

    t = ...
        sqrt(y) ...
        .* ( ...
        y .* f ...
        + g.a ...
    );

end

%% ========================================================================
% Stable upper-boundary TOF
% ========================================================================

function t = timeOfFlightUpperDistance(q, g)
    % q = 4*pi^2-z.
    %
    % Avoids subtracting
    %
    %       pi - sqrt(z)/2
    %
    % directly.

    boundary = ...
        4 * pi ^ 2;

    rootZ = ...
        sqrt( ...
        boundary - q ...
    );

    w = ...
        q ...
        ./ ( ...
        2 ...
        .* ( ...
        2 * pi ...
        + rootZ ...
    ) ...
    );

    u = ...
        pi - w;

    s = ...
        sin(w);

    cw = ...
        cos(w);

    if g.b < 0

        y = ...
            g.yend ...
            - 2 * g.b ...
            .* sin(w / 2) .^ 2;
    else

        y = ...
            g.y0 ...
            + 2 * g.b ...
            .* cos(w / 2) .^ 2;

    end

    numerator = ...
        u ...
        + s .* cw;

    f = ...
        numerator ...
        ./ ( ...
        sqrt(2) ...
        .* s .^ 3 ...
    );

    t = ...
        sqrt(y) ...
        .* ( ...
        y .* f ...
        + g.a ...
    );

end

%% ========================================================================
% Zero-revolution solver
% ========================================================================

function [z, status, qUpper, hyperbolicY] = solveZeroRev(g, t, fast)

    z = NaN;
    status = -4;

    qUpper = NaN;
    hyperbolicY = NaN;

    if fast

        targetTolerance = ...
            1e-11;

        globalNodes = ...
            [6 12 24];

        localNodes = ...
            [8 16 32];
    else

        targetTolerance = ...
            5e-13;

        globalNodes = ...
            [16 32 64];

        localNodes = ...
            [16 32 64 128];

    end

    %% -------------------------------------------------------------------
    % Parabolic time
    % --------------------------------------------------------------------

    tp = ...
        sqrt(g.y0) ...
        * ( ...
        g.y0 * sqrt(2) / 3 ...
        + g.a ...
    );

    if ~isfinite(tp) || ...
            tp <= 0

        return
    end

    %% -------------------------------------------------------------------
    % True / numerically indistinguishable parabola
    % --------------------------------------------------------------------

    residual0 = ...
        relativeResidual( ...
        0, ...
        g, ...
        0, ...
        t ...
    );

    if residual0 <= targetTolerance

        z = 0;
        status = 0;

        return
    end

    %% ===================================================================
    % Hyperbolic
    % ====================================================================

    if t < tp
        if g.b > 0
            [z, hyperbolicY, ok] = solveHyperbolicSqrtY(g, t);
            if ok, status = 0; end
            return
        end

        [candidate, residual, ok] = ...
            solveHyperbolicZeroRev( ...
            g, ...
            t, ...
            fast, ...
            targetTolerance ...
        );

        if ok

            z = candidate;
            status = 0;

        end

        return
    end

    %% ===================================================================
    % Elliptic long-way
    %
    % Solve directly in q = 4*pi^2-z.
    %
    % This is both faster and more accurate than first solving in z.
    % ====================================================================

    if g.b < 0

        [candidate, qCandidate, residual, ok] = ...
            solveUpperEllipticBoundary( ...
            g, ...
            t, ...
            localNodes, ...
            targetTolerance ...
        );

        if ok

            z = candidate;
            qUpper = qCandidate;
            status = 0;

        end

        return
    end

    %% ===================================================================
    % Elliptic short-way
    % ====================================================================

    zEstimate = ...
        estimateNearZeroZ( ...
        g, ...
        t, ...
        tp ...
    );

    % --------------------------------------------------------------------
    % If the root appears close to z=0, solve locally first.
    % --------------------------------------------------------------------

    if isfinite(zEstimate) && ...
            zEstimate > 0 && ...
            zEstimate < 0.25

        [candidate, residual, ok] = ...
            solveLowerEllipticBoundary( ...
            g, ...
            t, ...
            zEstimate, ...
            localNodes, ...
            targetTolerance ...
        );

        if ok

            z = candidate;
            status = 0;

            return
        end
    end

    %% -------------------------------------------------------------------
    % Interior short-way contour
    % --------------------------------------------------------------------

    [candidate, residual, ok] = ...
        solveEllipticInteriorZ( ...
        g, ...
        t, ...
        globalNodes, ...
        localNodes, ...
        targetTolerance ...
    );

    if ok

        z = candidate;
        status = 0;

        return
    end

    %% -------------------------------------------------------------------
    % Lower-boundary fallback
    % --------------------------------------------------------------------

    [candidate, residual, ok] = ...
        solveLowerEllipticBoundary( ...
        g, ...
        t, ...
        zEstimate, ...
        localNodes, ...
        targetTolerance ...
    );

    if ok

        z = candidate;
        status = 0;

    end
end

%% ========================================================================
% Estimate small positive z
% ========================================================================

function zEstimate = estimateNearZeroZ(g, t, tp)
    % Only estimates contour scale. It is NOT used as the Lambert solution.

    zEstimate = NaN;

    h1 = ...
        1e-3;

    h2 = ...
        5e-4;

    t1 = ...
        real( ...
        timeOfFlight( ...
        h1, ...
        g, ...
        0 ...
    ) ...
    );

    t2 = ...
        real( ...
        timeOfFlight( ...
        h2, ...
        g, ...
        0 ...
    ) ...
    );

    d1 = ...
        (t1 - tp) ...
        / h1;

    d2 = ...
        (t2 - tp) ...
        / h2;

    % Richardson improvement of the first derivative estimate.
    dTdz = ...
        2 * d2 ...
        - d1;

    if ~isfinite(dTdz) || ...
            dTdz <= 0

        return
    end

    zEstimate = ...
        (t - tp) ...
        / dTdz;

    if ~isfinite(zEstimate) || ...
            zEstimate <= 0

        zEstimate = NaN;

    end
end

%% ========================================================================
% Short-way interior z solver
% ========================================================================

function [bestZ, bestResidual, ok] = ...
        solveEllipticInteriorZ( ...
        g, ...
        t, ...
        globalNodes, ...
        localNodes, ...
        targetTolerance)

    bestZ = NaN;
    bestResidual = Inf;

    ok = false;

    boundary = ...
        4 * pi ^ 2;

    center = ...
        2 * pi ^ 2;

    epsilonList = ...
        [0.5 0.1 0.02];

    for n = globalNodes
        for epsilonContour = epsilonList

            radius = ...
                2 * pi ^ 2 ...
                - epsilonContour;

            contourLeft = ...
                center - radius;

            contourRight = ...
                center + radius;

            [candidate, contourOK] = ...
                contourPole( ...
                g, ...
                t, ...
                0, ...
                center, ...
                radius, ...
                n ...
            );

            if ~contourOK || ...
                    ~isfinite(candidate)

                continue
            end

            if candidate <= contourLeft || ...
                    candidate >= contourRight

                continue
            end

            residual = ...
                relativeResidual( ...
                candidate, ...
                g, ...
                0, ...
                t ...
            );

            if residual < bestResidual

                bestResidual = residual;
                bestZ = candidate;

            end

            if residual <= targetTolerance

                ok = true;

                return
            end

            [refined, refinedResidual] = ...
                refineZCandidate( ...
                candidate, ...
                g, ...
                t, ...
                localNodes, ...
                targetTolerance, ...
                boundary ...
            );

            if refinedResidual < bestResidual

                bestResidual = refinedResidual;
                bestZ = refined;

            end

            if bestResidual <= targetTolerance

                ok = true;

                return
            end
        end
    end
end

%% ========================================================================
% Near-z=0 local solver
% ========================================================================

function [bestZ, bestResidual, ok] = ...
        solveLowerEllipticBoundary( ...
        g, ...
        t, ...
        zEstimate, ...
        nodeCounts, ...
        targetTolerance)
    %SOLVELOWERELLIPTICBOUNDARY Robust z -> 0+ contour solution.
    %
    % Uses:
    %
    %   1. Local TOF-derived z estimate
    %   2. Multiplicative contours around that estimate
    %   3. Fully overlapping logarithmic fallback contours
    %   4. Small recentered contour when necessary
    %
    % Adjacent fallback contours overlap, so there are no uncovered
    % positive-z intervals.

    bestZ = NaN;
    bestResidual = Inf;

    ok = false;

    %% ===================================================================
    % Estimate-driven centers
    % ====================================================================

    centers = [];

    if isfinite(zEstimate) && ...
            zEstimate > 0

        % Try the estimated scale first.
        %
        % These overlap heavily and account for moderate errors in the
        % parabolic linearization.
        multipliers = [ ...
                           1, ...
                           0.5, ...
                           2, ...
                           0.25, ...
                           4, ...
                           0.1, ...
                           10 ...
                       ];

        estimateCenters = ...
            zEstimate ...
            .* multipliers;

        estimateCenters = ...
            estimateCenters( ...
            estimateCenters > 0 ...
            & estimateCenters < 1 ...
        );

        centers = ...
            estimateCenters;

    end

    %% ===================================================================
    % Logarithmic fallback
    %
    % IMPORTANT:
    %
    % Use EVERY decade rather than every two decades.
    %
    % radius = 0.95*center gives:
    %
    %       0.05*s < z < 1.95*s
    %
    % while the next decade gives:
    %
    %       0.5*s < z < 19.5*s
    %
    % so adjacent contours overlap substantially.
    % ====================================================================

    fallbackCenters = ...
        10 .^ (-22:0);

    % If we have an estimate, search fallback decades nearest the
    % estimated scale first.
    if isfinite(zEstimate) && ...
            zEstimate > 0

        logEstimate = ...
            log10(zEstimate);

        [~, order] = ...
            sort( ...
            abs( ...
            log10(fallbackCenters) ...
            - logEstimate ...
        ) ...
        );

        fallbackCenters = ...
            fallbackCenters(order);

    end

    centers = ...
        unique( ...
        [centers fallbackCenters], ...
        'stable' ...
    );

    %% ===================================================================
    % Search contours
    % ====================================================================

    for center = centers
        if ~isfinite(center) || ...
                center <= 0 || ...
                center >= 1

            continue
        end

        % ---------------------------------------------------------------
        % 95% radius is intentional.
        %
        % It gives broad overlapping scale coverage while still keeping
        % the contour away from z = 0.
        % ---------------------------------------------------------------

        radius = ...
            0.95 ...
            * center;

        contourLeft = ...
            center - radius;

        contourRight = ...
            center + radius;

        for n = nodeCounts

            [candidate, contourOK] = ...
                contourPole( ...
                g, ...
                t, ...
                0, ...
                center, ...
                radius, ...
                n ...
            );

            if ~contourOK || ...
                    ~isfinite(candidate)

                continue
            end

            % Candidate must actually lie in this contour.
            if candidate <= contourLeft || ...
                    candidate >= contourRight

                continue
            end

            if candidate <= 0 || ...
                    candidate >= 4 * pi ^ 2

                continue
            end

            residual = ...
                relativeResidual( ...
                candidate, ...
                g, ...
                0, ...
                t ...
            );

            if residual < bestResidual

                bestResidual = residual;
                bestZ = candidate;

            end

            %% -----------------------------------------------------------
            % Already accurate enough
            % ------------------------------------------------------------

            if residual <= targetTolerance

                ok = true;

                return
            end

            %% -----------------------------------------------------------
            % Recenter around the actual candidate.
            %
            % Once the large local contour locates the pole approximately,
            % a much smaller contour converges rapidly.
            % ------------------------------------------------------------

            distanceLower = ...
                candidate;

            distanceUpper = ...
                4 * pi ^ 2 ...
                - candidate;

            localRadius = ...
                0.5 ...
                * min( ...
                distanceLower, ...
                distanceUpper ...
            );

            if ~isfinite(localRadius) || ...
                    localRadius <= 0

                continue
            end

            localLeft = ...
                candidate ...
                - localRadius;

            localRight = ...
                candidate ...
                + localRadius;

            % Usually only a small number of nodes are necessary here.
            refineNodes = ...
                unique( ...
                [ ...
                 nodeCounts, ...
                 64 ...
             ], ...
                'stable' ...
            );

            for nr = refineNodes

                [refined, refineOK] = ...
                    contourPole( ...
                    g, ...
                    t, ...
                    0, ...
                    candidate, ...
                    localRadius, ...
                    nr ...
                );

                if ~refineOK || ...
                        ~isfinite(refined)

                    continue
                end

                if refined <= localLeft || ...
                        refined >= localRight

                    continue
                end

                refinedResidual = ...
                    relativeResidual( ...
                    refined, ...
                    g, ...
                    0, ...
                    t ...
                );

                if refinedResidual < bestResidual

                    bestResidual = ...
                        refinedResidual;

                    bestZ = ...
                        refined;

                end

                if refinedResidual <= targetTolerance

                    ok = true;

                    return
                end
            end
        end
    end

    %% ===================================================================
    % Final acceptance
    % ====================================================================

    if isfinite(bestZ) && ...
            bestResidual <= targetTolerance

        ok = true;

    end
end

%% ========================================================================
% Refine an existing z contour estimate
% ========================================================================

function [bestZ, bestResidual] = ...
        refineZCandidate( ...
        initialZ, ...
        g, ...
        t, ...
        nodeCounts, ...
        targetTolerance, ...
        upperBoundary)

    bestZ = ...
        initialZ;

    bestResidual = ...
        relativeResidual( ...
        initialZ, ...
        g, ...
        0, ...
        t ...
    );

    if bestResidual <= targetTolerance
        return
    end

    center = ...
        initialZ;

    distance = ...
        min( ...
        center, ...
        upperBoundary - center ...
    );

    if distance <= 0
        return
    end

    baseRadius = ...
        min( ...
        2, ...
        0.75 * distance ...
    );

    radiusFractions = ...
        [1 0.25 0.0625];

    for fraction = radiusFractions

        radius = ...
            baseRadius ...
            * fraction;

        if radius <= 0
            continue
        end

        contourLeft = ...
            center - radius;

        contourRight = ...
            center + radius;

        for n = nodeCounts

            [candidate, contourOK] = ...
                contourPole( ...
                g, ...
                t, ...
                0, ...
                center, ...
                radius, ...
                n ...
            );

            if ~contourOK || ...
                    ~isfinite(candidate)

                continue
            end

            if candidate <= contourLeft || ...
                    candidate >= contourRight

                continue
            end

            residual = ...
                relativeResidual( ...
                candidate, ...
                g, ...
                0, ...
                t ...
            );

            if residual < bestResidual

                bestResidual = residual;
                bestZ = candidate;
                center = candidate;

            end

            if bestResidual <= targetTolerance
                return
            end
        end
    end
end

%% ========================================================================
% Long-way elliptic solver in q = 4*pi^2-z
% ========================================================================

function [z, qRoot, bestResidual, ok] = ...
        solveUpperEllipticBoundary( ...
        g, ...
        t, ...
        nodeCounts, ...
        targetTolerance)

    boundary = ...
        4 * pi ^ 2;

    z = NaN;
    qRoot = NaN;

    bestQ = NaN;
    bestResidual = Inf;

    ok = false;

    %% -------------------------------------------------------------------
    % Asymptotic q estimate
    %
    % As q -> 0:
    %
    % T ~ C/q^3
    %
    % C = 512*pi^4*yend^(3/2)/sqrt(2)
    % --------------------------------------------------------------------

    guesses = [];

    if isfinite(g.yend) && ...
            g.yend > 0 && ...
            t > 0

        C = ...
            512 ...
            * pi ^ 4 ...
            * g.yend ^ (3/2) ...
            / sqrt(2);

        qEstimate = ...
            (C / t) ^ (1/3);

        if isfinite(qEstimate) && ...
                qEstimate > 0 && ...
                qEstimate < boundary

            guesses(end + 1) = ...
                qEstimate;

        end
    end

    % Generic interior fallback estimate.
    guesses(end + 1) = ...
        boundary / 4;

    %% -------------------------------------------------------------------
    % Multiplicative centers
    %
    % One asymptotic estimate usually solves the case immediately.
    % --------------------------------------------------------------------

    multipliers = [ ...
                       1, ...
                       0.5, ...
                       2, ...
                       0.25, ...
                       4, ...
                       0.125, ...
                       8 ...
                   ];

    centers = [];

    for guess = guesses

        values = ...
            guess .* multipliers;

        values = ...
            values( ...
            values > 0 ...
            & values < boundary ...
        );

        centers = ...
            [centers values]; %#ok<AGROW>

    end

    centers = ...
        unique(centers, 'stable');

    %% -------------------------------------------------------------------
    % Estimate-driven local contours
    % --------------------------------------------------------------------

    for center = centers

        distanceUpper = ...
            boundary - center;

        radius = ...
            min( ...
            0.85 * center, ...
            0.85 * distanceUpper ...
        );

        if ~isfinite(radius) || ...
                radius <= 0

            continue
        end

        contourLeft = ...
            center - radius;

        contourRight = ...
            center + radius;

        for n = nodeCounts

            [candidateQ, contourOK] = ...
                contourPoleUpperDistance( ...
                g, ...
                t, ...
                center, ...
                radius, ...
                n ...
            );

            if ~contourOK || ...
                    ~isfinite(candidateQ)

                continue
            end

            if candidateQ <= contourLeft || ...
                    candidateQ >= contourRight || ...
                    candidateQ <= 0 || ...
                    candidateQ >= boundary

                continue
            end

            residual = ...
                relativeResidualUpper( ...
                candidateQ, ...
                g, ...
                t ...
            );

            if residual < bestResidual

                bestResidual = residual;
                bestQ = candidateQ;

            end

            if residual <= targetTolerance

                qRoot = candidateQ;

                z = ...
                    boundary - qRoot;

                ok = true;

                return
            end

            [refinedQ, refinedResidual] = ...
                refineQCandidate( ...
                candidateQ, ...
                g, ...
                t, ...
                nodeCounts, ...
                targetTolerance, ...
                boundary ...
            );

            if refinedResidual < bestResidual

                bestResidual = refinedResidual;
                bestQ = refinedQ;

            end

            if bestResidual <= targetTolerance

                qRoot = bestQ;

                z = ...
                    boundary - qRoot;

                ok = true;

                return
            end
        end
    end

    %% -------------------------------------------------------------------
    % Global q fallback
    %
    % This is only reached when the estimator-driven path fails.
    % --------------------------------------------------------------------

    center = ...
        boundary / 2;

    exclusions = ...
        [0.5 0.05 0.005 5e-4];

    fallbackNodes = ...
        unique( ...
        [nodeCounts 64], ...
        'stable' ...
    );

    for exclusion = exclusions

        radius = ...
            boundary / 2 ...
            - exclusion;

        if radius <= 0
            continue
        end

        contourLeft = ...
            center - radius;

        contourRight = ...
            center + radius;

        for n = fallbackNodes

            [candidateQ, contourOK] = ...
                contourPoleUpperDistance( ...
                g, ...
                t, ...
                center, ...
                radius, ...
                n ...
            );

            if ~contourOK || ...
                    ~isfinite(candidateQ)

                continue
            end

            if candidateQ <= contourLeft || ...
                    candidateQ >= contourRight

                continue
            end

            residual = ...
                relativeResidualUpper( ...
                candidateQ, ...
                g, ...
                t ...
            );

            if residual < bestResidual

                bestResidual = residual;
                bestQ = candidateQ;

            end

            [refinedQ, refinedResidual] = ...
                refineQCandidate( ...
                candidateQ, ...
                g, ...
                t, ...
                nodeCounts, ...
                targetTolerance, ...
                boundary ...
            );

            if refinedResidual < bestResidual

                bestResidual = refinedResidual;
                bestQ = refinedQ;

            end

            if bestResidual <= targetTolerance

                qRoot = bestQ;

                z = ...
                    boundary - qRoot;

                ok = true;

                return
            end
        end
    end

    %% -------------------------------------------------------------------
    % Final acceptance
    % --------------------------------------------------------------------

    if isfinite(bestQ) && ...
            bestResidual <= targetTolerance

        qRoot = bestQ;

        z = ...
            boundary - qRoot;

        ok = true;

    end
end

