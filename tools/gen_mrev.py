"""Generate multi-revolution tables for the contour solver (ID 0).
usage: python tools/gen_mrev.py NTAU NSIG OUT.inc [NC]  (shipped: 16 24 OUT 128)
Slices in mu = 1/m: m = 1,2,3,4,6,8,12,16,32 and m = 1e6 (~infinity).
  mr_v (ntau, nsig, nslice): branch root v in (0,pi), sigma = b*sqrt(1-(Tmin/t)^(1/3))
  mr_c (ntau, nslice):       cbrt(Tmin/m)/sqrt(s_L) (scale-free)
  mr_s (ntau, nslice):       v* (location of the minimum time)."""
import sys
import numpy as np
from mrev_table import branch_root, tmin, TM
M = [1, 2, 3, 4, 6, 8, 12, 16, 32, 1000000]
nt, ns, out = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3]
nc = int(sys.argv[4]) if len(sys.argv) > 4 else 256   # fine tau grid for Tmin and v*
Tg = np.linspace(-TM, TM, nt); Lg = 2 * Tg / (1 + Tg * Tg); Sg = np.linspace(-1, 1, ns)
LL, SS = np.meshgrid(Lg, np.clip(Sg, -1 + 1e-9, 1 - 1e-9), indexing='ij')
Tc = np.linspace(-TM, TM, nc); Lc = 2 * Tc / (1 + Tc * Tc)
V = np.zeros((nt, ns, len(M))); C = np.zeros((nc, len(M))); VS = np.zeros((nc, len(M)))
for k, m in enumerate(M):
    V[:, :, k], _ = branch_root(LL, SS, m)
    tm, vs = tmin(Lc, m)
    # T scales as s_L**1.5: store cbrt(Tmin/m)/sqrt(s_L) for the canonical
    # geometry (r1 = r2 = 1, s_L = 2/(1+lam^2)); multiply by sqrt(s_L) at run time.
    C[:, k] = np.cbrt(tm / m) / np.sqrt(2 / (1 + Lc * Lc)); VS[:, k] = vs
def arr(f, name, A):
    vals = A.ravel(order='F'); shp = ",".join(str(x) for x in A.shape)
    f.write(f"   real(dp),parameter::{name}({shp})=reshape([ &\n")
    f.write(", &\n".join("      " + ",".join(f"{x:.17e}_dp" for x in vals[k:k+4]) for k in range(0, len(vals), 4)))
    f.write(f"],[{shp}])\n")
with open(out, 'w') as f:
    f.write(f"   ! Generated by tools/gen_mrev.py {nt} {ns} OUT {nc}; do not edit.\n")
    f.write(f"   integer,parameter::mr_nt={nt},mr_ns={ns},mr_nm={len(M)},mr_nc={nc}\n")
    f.write(f"   real(dp),parameter::mr_tmax={TM}_dp\n")
    f.write("   real(dp),parameter::mr_mu(mr_nm)=[" + ",".join(f"{1/m:.17e}_dp" for m in M) + "]\n")
    f.write("   integer,parameter::mr_m(mr_nm)=[" + ",".join(str(m) for m in M) + "]\n")
    arr(f, "mr_v", V); arr(f, "mr_c", C); arr(f, "mr_s", VS)
print("wrote", out, "KB:", (V.size + C.size + VS.size) * 8 / 1024)
