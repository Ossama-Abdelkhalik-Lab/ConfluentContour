"""Generate the zero-revolution elliptic estimate tables for the contour solver (ID 0).
usage: python tools/gen_table.py N OUT.inc  (shipped: N=32)
Grid: tau = lam/(1+sqrt(1-lam^2)) uniform on [-TM, TM]; s = (tp/t)^(1/3)
uniform on [0,1/2] (table A = (pi - v)/s) and [1/2,1] (table B = z/(1-s)).
Truth: bisection on the zero-revolution T(v) in double precision, with the
parabolic series for v < 0.3 (as in the solver), canonical geometry
r1 = r2 = 1 (the root depends only on lambda and s)."""
import sys
import numpy as np
S2 = np.sqrt(2.0); PI = np.pi; TM = 0.995
PSER = np.array([115665628927/2601853536522240000, 3821869001/10751460894720000,
        133541/48117888000, 763967/36324288000, 1393481/9081072000,
        1181/1108800, 29/4200, 17/420, 1/5, 2/3])

def geom(lam):
    d = np.where(lam >= 0, 1.0, -1.0)
    sh = (1 - lam * lam) / (1 + lam * lam); cs = np.sqrt(np.maximum(0, 1 - sh * sh)); ss = sh
    a = d * S2 * cs; b = S2 * a
    y0 = np.where(d > 0, 2 * ss * ss / (1 + cs), 2 * (1 + cs)); yend = 2 * ss * ss / (1 + cs)
    tp = np.sqrt(y0) * (y0 * S2 / 3 + a)
    return a, b, y0, yend, tp

def T_v(v, a, b, y0, yend):
    sh, ch = np.sin(v / 2), np.cos(v / 2)
    y = np.where(b < 0, yend - 2 * b * ch * ch, y0 + 2 * b * sh * sh)
    sv, cv = np.sin(v), np.cos(v)
    x = v * v; ser = np.zeros_like(v)
    for p in PSER: ser = ser * x + p
    F = np.where(v < .3, ser / S2, (v - sv * cv) / (S2 * sv ** 3))
    return np.sqrt(y) * (y * F + a)

def root_v(lam, s):
    a, b, y0, yend, tp = geom(lam); t = tp / s ** 3
    lo = np.zeros_like(lam); hi = np.full(lam.shape, PI)
    for _ in range(70):
        m = 0.5 * (lo + hi)
        f = T_v(m, a, b, y0, yend) < t
        lo = np.where(f, m, lo); hi = np.where(f, hi, m)
    return 0.5 * (lo + hi)

def tables(n):
    T = np.linspace(-TM, TM, n); L = 2 * T / (1 + T * T)
    Su = np.linspace(0, .5, n); Sl = np.linspace(.5, 1, n)
    LL, SU = np.meshgrid(L, Su, indexing='ij'); _, SL = np.meshgrid(L, Sl, indexing='ij')
    SUc = np.maximum(SU, 1e-7); SLc = np.minimum(SL, 1 - 1e-7)
    A = (PI - root_v(LL, SUc)) / SUc
    B = 4 * root_v(LL, SLc) ** 2 / (1 - SLc)
    return A, B

if __name__ == "__main__":
    n = int(sys.argv[1]); out = sys.argv[2]
    A, B = tables(n)
    with open(out, 'w') as f:
        f.write(f"   ! Generated by tools/gen_table.py {n}; do not edit.\n")
        f.write(f"   ! Zero-revolution elliptic root tables on tau = lam/(1+sqrt(1-lam**2))\n")
        f.write(f"   ! in [-{TM},{TM}] x s = (tp/t)**(1/3): A = (pi-v)/s on [0,1/2], B = z/(1-s) on [1/2,1].\n")
        f.write(f"   integer,parameter::tab_n={n}\n   real(dp),parameter::tab_tmax={TM}_dp\n")
        for name, M in (("tab_a", A), ("tab_b", B)):
            vals = M.T.ravel()          # Fortran column-major: tab(i_tau, j_s)
            f.write(f"   real(dp),parameter::{name}({n},{n})=reshape([ &\n")
            lines = []
            for k in range(0, len(vals), 4):
                lines.append("      " + ",".join(f"{x:.17e}_dp" for x in vals[k:k+4]))
            f.write(", &\n".join(lines) + "],[" + f"{n},{n}" + "])\n")
    print("wrote", out, A.shape, "A range", A.min(), A.max(), "B range", B.min(), B.max())
